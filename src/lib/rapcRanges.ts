export function buildSeedRapcRanges() {
  const timestamp = new Date().toISOString();
  return RAPC_RANGE_SEED_ROWS.map(([from, to, rapcRange], index) => ({
    id: `rapc-range-seed-${index + 1}`,
    from,
    to,
    rapcRange,
    updatedBy: "System Seed",
    updateTimestamp: timestamp,
  })) satisfies RapcRange[];
}

export function getEffectiveRapcRanges(ranges: RapcRange[]) {
  return ranges.length > 0 ? ranges : buildSeedRapcRanges();
}

export function resolveRapcRange(input: number | string | undefined | null, ranges: RapcRange[]) {
  const numericInput = Number(input);
  if (!Number.isFinite(numericInput)) return 0;
  const source = getEffectiveRapcRanges(ranges);
  const match = source.find((row) => numericInput >= Number(row.from || 0) && numericInput <= Number(row.to || 0));
  return Number(match?.rapcRange || 0);
}
